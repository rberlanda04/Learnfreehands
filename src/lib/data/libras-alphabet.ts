/**
 * Lista de letras suportadas pelo classificador de IA
 */
export const SUPPORTED_LETTERS = LIBRAS_ALPHABET
  .filter((s) => s.supported)
  .map((s) => s.letter!);

/**
 * Retorna dados de uma letra específica
 */
export function getLetterData(letter: string): LibrasSign | undefined {
  return LIBRAS_ALPHABET.find(
    (s) => s.letter?.toUpperCase() === letter.toUpperCase()
  );
}
